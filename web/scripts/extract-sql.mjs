#!/usr/bin/env node
// Extracts views, functions, policies and triggers VERBATIM from the Supabase migrations
// into src/sql/sources.generated.ts, so the "Show the SQL" drawer can never drift from
// the database. Run: npm run sql:extract   (read-only: it never touches supabase/**).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const migrationsDir = path.resolve(here, '../../supabase/migrations')
const outFile = path.resolve(here, '../src/sql/sources.generated.ts')

const files = readdirSync(migrationsDir)
  .filter((f) => /^\d+_.+\.sql$/.test(f) && !f.includes('core_schema'))
  .sort()

/** The comment lines (`-- ...`) directly above `index` in `text`, verbatim. */
function leadingComments(text, index) {
  const before = text.slice(0, index).split('\n')
  before.pop() // the partial line the statement starts on (empty)
  const out = []
  while (before.length) {
    const line = before[before.length - 1]
    if (/^\s*--/.test(line) && !/^\s*-- =+\s*$/.test(line)) {
      out.unshift(line)
      before.pop()
    } else break
  }
  return out.join('\n')
}

const views = {}
const functions = {}
const policies = {}
const triggers = {}

for (const file of files) {
  const text = readFileSync(path.join(migrationsDir, file), 'utf8')

  for (const m of text.matchAll(/^CREATE VIEW (\w+)[\s\S]*?;[ \t]*(?:--[^\n]*)?$/gm)) {
    views[m[1]] = { file, comment: leadingComments(text, m.index), sql: m[0].trimEnd() }
  }
  for (const m of text.matchAll(/^CREATE FUNCTION ([\w.]+)\([\s\S]*?\$\$;\s*$/gm)) {
    functions[m[1]] = { file, comment: leadingComments(text, m.index), sql: m[0].trimEnd() }
  }
  for (const m of text.matchAll(/^CREATE POLICY (\w+) ON (\w+)[\s\S]*?;[ \t]*(?:--[^\n]*)?$/gm)) {
    policies[m[1]] = { file, table: m[2], generated: false, sql: m[0].trimEnd() }
  }
  for (const m of text.matchAll(
    /^CREATE TRIGGER (\w+)\s+[\s\S]*?\bON (\w+)[\s\S]*?EXECUTE FUNCTION ([\w.]+)\([^)]*\);\s*$/gm,
  )) {
    triggers[m[1]] = { file, table: m[2], fn: m[3], sql: m[0].trimEnd() }
  }

  // 0003 §3 generates the uniform directory-table policies in a DO loop. Reconstruct the
  // statement each EXECUTE format(...) produces, and say where it came from.
  const loops = [...text.matchAll(/FOREACH t IN ARRAY ARRAY\[([^\]]+)\]\s*LOOP([\s\S]*?)END LOOP;/g)]
  for (const loop of loops) {
    const tables = [...loop[1].matchAll(/'(\w+)'/g)].map((x) => x[1])
    const formats = [...loop[2].matchAll(/format\(((?:'[^']*'\s*)+),\s*t \|\| '(_\w+)', t\)/g)]
    for (const f of formats) {
      const template = [...f[1].matchAll(/'([^']*)'/g)].map((x) => x[1]).join('')
      for (const t of tables) {
        const name = t + f[2]
        if (policies[name]) continue
        const sql = template.replace('%I', name).replace('%I', t)
        policies[name] = {
          file,
          table: t,
          generated: true,
          sql: `-- generated by the DO $$ … FOREACH t IN ARRAY … $$ block (${file} §3)\n${sql};`,
        }
      }
    }
  }
}

const header = `// AUTO-GENERATED by web/scripts/extract-sql.mjs from supabase/migrations/*.sql.
// Do not edit by hand: run \`npm run sql:extract\` after a migration changes.
/* eslint-disable */
`
const body = [
  `export const VIEW_SQL = ${JSON.stringify(views, null, 2)} as const satisfies Record<string, { file: string; comment: string; sql: string }>`,
  `export const FUNCTION_SQL = ${JSON.stringify(functions, null, 2)} as const satisfies Record<string, { file: string; comment: string; sql: string }>`,
  `export const POLICY_SQL = ${JSON.stringify(policies, null, 2)} as const satisfies Record<string, { file: string; table: string; generated: boolean; sql: string }>`,
  `export const TRIGGER_SQL = ${JSON.stringify(triggers, null, 2)} as const satisfies Record<string, { file: string; table: string; fn: string; sql: string }>`,
  `export type ViewName = keyof typeof VIEW_SQL`,
  `export type FunctionName = keyof typeof FUNCTION_SQL`,
  `export type PolicyName = keyof typeof POLICY_SQL`,
  `export type TriggerName = keyof typeof TRIGGER_SQL`,
].join('\n\n')

writeFileSync(outFile, header + '\n' + body + '\n')
console.log(
  `sql:extract -> ${path.relative(process.cwd(), outFile)}: ` +
    `${Object.keys(views).length} views, ${Object.keys(functions).length} functions, ` +
    `${Object.keys(policies).length} policies, ${Object.keys(triggers).length} triggers`,
)
