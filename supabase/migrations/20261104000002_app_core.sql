-- ---- (i) Countersign: a teammate of the claimant, never the claimant, on the text they saw ----
-- Locks the claim row (FOR NO KEY UPDATE): an edit of the claim and a countersign cannot
-- interleave. claim_revision is the revision the endorser read; if the claim changed since,
-- the signature is refused (optimistic concurrency control). Left NULL, it is filled in
-- with the current revision (the RPC passes what the UI showed).
-- The claim's component must be open: a countersign is neither added, changed nor
-- withdrawn after the lock (withdrawing would reopen a locked claim for editing).
CREATE FUNCTION private.check_countersign()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE c RECORD;
BEGIN
    SELECT usn, team_id, project_id, milestone_no, revision INTO c
    FROM public.claim
    WHERE claim_id = CASE WHEN TG_OP = 'DELETE' THEN OLD.claim_id ELSE NEW.claim_id END
    FOR NO KEY UPDATE;
    IF NOT FOUND THEN                                -- cascade from deleting the claim,
        RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;   -- or the FK reports it
    END IF;
    PERFORM private.assert_milestone_open(c.project_id, c.milestone_no, 'its countersigns');
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    IF NEW.endorser_usn = c.usn THEN
        RAISE EXCEPTION 'Student % cannot countersign their own claim %', NEW.endorser_usn, NEW.claim_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'countersign_not_self',
                  DETAIL = 'countersign_not_self';
    END IF;
    PERFORM private.assert_team_member(c.team_id, NEW.endorser_usn, 'countersign_teammate_required');

    IF NEW.claim_revision IS NULL THEN
        NEW.claim_revision := c.revision;
    ELSIF NEW.claim_revision <> c.revision THEN
        RAISE EXCEPTION 'Claim % changed after you read it (revision % -> %); read it again before signing',
            NEW.claim_id, NEW.claim_revision, c.revision
            USING ERRCODE = 'object_not_in_prerequisite_state', CONSTRAINT = 'countersign_stale_revision',
                  DETAIL = 'countersign_stale_revision';
    END IF;
    -- a revised verdict is a new signature: the server stamps the time
    IF TG_OP = 'UPDATE' AND (NEW.verdict, NEW.comment) IS DISTINCT FROM (OLD.verdict, OLD.comment) THEN
        NEW.signed_at := now();
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_countersign_check
BEFORE INSERT OR UPDATE OR DELETE ON countersign
FOR EACH ROW EXECUTE FUNCTION private.check_countersign();

-- claim.status is derived from its countersigns: any dispute -> contested;
-- else at least one confirm -> confirmed; else pending.
-- (Every endorser is a current teammate: guard_member_history keeps an endorser in the team.)
CREATE FUNCTION private.claim_status(p_claim_id INT)
RETURNS VARCHAR LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
    SELECT CASE
               WHEN bool_or(verdict = 'dispute') THEN 'contested'
               WHEN bool_or(verdict = 'confirm') THEN 'confirmed'
               ELSE 'pending'
           END
    FROM public.countersign
    WHERE claim_id = p_claim_id;
$$;

-- Any write to claim recomputes status, so it cannot be set by hand (tamper-proof).
CREATE FUNCTION private.derive_claim_status()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
    NEW.status := private.claim_status(NEW.claim_id);
    RETURN NEW;
END $$;

CREATE TRIGGER trg_claim_status_derived
BEFORE INSERT OR UPDATE ON claim
FOR EACH ROW EXECUTE FUNCTION private.derive_claim_status();

-- After a countersign changes, touch the claim so the trigger above recomputes status.
CREATE FUNCTION private.sync_claim_status()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        UPDATE public.claim SET status = private.claim_status(claim_id) WHERE claim_id = NEW.claim_id;
    END IF;
    IF TG_OP = 'DELETE' OR (TG_OP = 'UPDATE' AND OLD.claim_id <> NEW.claim_id) THEN
        UPDATE public.claim SET status = private.claim_status(claim_id) WHERE claim_id = OLD.claim_id;
    END IF;
    RETURN NULL;
END $$;

CREATE TRIGGER trg_countersign_sync_status
AFTER INSERT OR UPDATE OR DELETE ON countersign
FOR EACH ROW EXECUTE FUNCTION private.sync_claim_status();

