-- =====================================================================
-- 11. Integrity triggers: cross-row / cross-table rules a CHECK cannot express.
--     All are SECURITY DEFINER with an empty search_path, so (a) they see every row
--     regardless of the caller's RLS, and (b) nothing can be hijacked via search_path.
--     Errors use real SQLSTATEs plus a CONSTRAINT name the web app maps to a field.
-- =====================================================================

-- ---- helper: raise unless p_usn is a member of p_team_id ----
-- Without care this is WRITE SKEW: one transaction checks "X is a member" and records X's
-- work, while another checks "X has no work" and deletes X's membership; each check passes
-- on its own snapshot. So the check WRITES the membership row it relies on (a no-op UPDATE,
-- the same "serialize by writing" idea as capacity v2 below). A concurrent DELETE of that
-- row then waits for us and, under READ COMMITTED, its history guard re-reads and sees our
-- row; under REPEATABLE READ / SERIALIZABLE it fails with 40001. (A lock alone, e.g. FOR
-- KEY SHARE, would not do: under RR the deleter's snapshot predates our commit, and a
-- row that was only locked, not changed, raises no serialization error.)
-- Cost: one student's concurrent writes in the same team queue on that one row.
CREATE FUNCTION private.assert_team_member(p_team_id VARCHAR, p_usn VARCHAR, p_rule TEXT)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
    UPDATE public.team_member SET role = role
    WHERE team_id = p_team_id AND usn = p_usn;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Student % is not a member of team %', p_usn, p_team_id
            USING ERRCODE = 'check_violation', CONSTRAINT = p_rule, DETAIL = p_rule;
    END IF;
END $$;

-- ---- helper: raise unless the component is still open (not locked) ----
-- FOR SHARE: a concurrent lock_milestone() UPDATE waits for this transaction, or we wait
-- for it and then see locked_at, so nothing slips in at lock time.
CREATE FUNCTION private.assert_milestone_open(p_project_id VARCHAR, p_milestone_no INT, p_what TEXT)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_locked TIMESTAMPTZ;
BEGIN
    SELECT locked_at INTO v_locked FROM public.milestone
    WHERE project_id = p_project_id AND milestone_no = p_milestone_no
    FOR SHARE;
    IF v_locked IS NOT NULL THEN
        RAISE EXCEPTION 'Milestone %/% is locked (since %); % can no longer change',
            p_project_id, p_milestone_no, v_locked, p_what
            USING ERRCODE = 'object_not_in_prerequisite_state', CONSTRAINT = 'milestone_locked',
                  DETAIL = 'milestone_locked';
    END IF;
END $$;

-- ---- (a) Team capacity v2: "serialize by writing the parent row" ----
-- Why v2: the fixture's check_team_capacity() (Q35) only SELECTs the team row FOR UPDATE.
-- Under REPEATABLE READ the snapshot is fixed before the lock wait and a lock is not a
-- write, so the second joiner counts a stale 3/4 and over-admits to 5/4
-- (experiments/race/FINDINGS.md). Here the trigger *writes* the team row (no-op UPDATE):
--   READ COMMITTED  -> the 2nd joiner waits, then the COUNT (new statement = new snapshot)
--                      sees the 1st joiner and is refused;
--   REPEATABLE READ / SERIALIZABLE -> the 2nd joiner's UPDATE hits a row changed after its
--                      snapshot: SQLSTATE 40001, the client retries and is then refused.
-- Fires on INSERT and on UPDATE OF team_id (moving teams must not bypass the rule).
CREATE FUNCTION private.enforce_team_capacity_v2()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
    cap          INT;
    current_size INT;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.team_id = OLD.team_id THEN
        RETURN NEW;                                  -- not changing team: size unchanged
    END IF;

    -- 1. write-lock the parent row (also creates a new row version => RR/SER conflict)
    UPDATE public.team SET max_size = max_size
    WHERE team_id = NEW.team_id
    RETURNING max_size INTO cap;
    IF NOT FOUND THEN
        RETURN NEW;                                  -- unknown team: the FK reports it
    END IF;

    -- 2. count only after the lock is held (the moving row is still under OLD.team_id)
    SELECT count(*) INTO current_size FROM public.team_member WHERE team_id = NEW.team_id;
    IF current_size >= cap THEN
        RAISE EXCEPTION 'Team % is full (% / %)', NEW.team_id, current_size, cap
            USING ERRCODE = 'check_violation', CONSTRAINT = 'team_capacity', DETAIL = 'team_capacity';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_team_capacity_v2
BEFORE INSERT OR UPDATE OF team_id ON team_member
FOR EACH ROW EXECUTE FUNCTION private.enforce_team_capacity_v2();

-- ---- (b) Capacity cannot be bypassed by shrinking max_size below the member count ----
CREATE FUNCTION private.guard_team_shrink()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE n INT;
BEGIN
    IF NEW.max_size < OLD.max_size THEN
        SELECT count(*) INTO n FROM public.team_member WHERE team_id = NEW.team_id;
        IF n > NEW.max_size THEN
            RAISE EXCEPTION 'Team % already has % members; max_size % is too small', NEW.team_id, n, NEW.max_size
                USING ERRCODE = 'check_violation', CONSTRAINT = 'team_capacity', DETAIL = 'team_capacity';
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_team_shrink_guard
BEFORE UPDATE OF max_size ON team
FOR EACH ROW EXECUTE FUNCTION private.guard_team_shrink();

-- ---- (c) One team per project per student ----
-- A cross-table rule (team_member.usn + team.project_id). Same write-lock trick, on the
-- student row, so two concurrent joins by one student into two teams serialize.
CREATE FUNCTION private.enforce_one_team_per_project()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
    v_project  VARCHAR(5);
    v_offering INT;
    v_other    VARCHAR(5);
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.team_id = OLD.team_id AND NEW.usn = OLD.usn THEN
        RETURN NEW;
    END IF;

    UPDATE public.student SET usn = usn WHERE usn = NEW.usn;  -- no-op write = row lock

    SELECT t.project_id, p.offering_id INTO v_project, v_offering
    FROM public.team t JOIN public.project p ON p.project_id = t.project_id
    WHERE t.team_id = NEW.team_id;

    -- TEAM_MEMBER must respect ENROLLMENT: only students enrolled in the project's course
    -- offering may join its teams. (Fixture projects have no offering: no rule to apply.)
    IF v_offering IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM public.enrollment WHERE usn = NEW.usn AND offering_id = v_offering) THEN
        RAISE EXCEPTION 'Student % is not enrolled in the course offering of project %', NEW.usn, v_project
            USING ERRCODE = 'check_violation', CONSTRAINT = 'team_member_enrolled_required',
                  DETAIL = 'team_member_enrolled_required';
    END IF;

    SELECT tm.team_id INTO v_other
    FROM public.team_member tm
    JOIN public.team t ON t.team_id = tm.team_id
    WHERE tm.usn = NEW.usn
      AND t.project_id = v_project
      AND tm.team_id <> NEW.team_id
      AND NOT (TG_OP = 'UPDATE' AND tm.team_id = OLD.team_id AND tm.usn = OLD.usn)
    LIMIT 1;

    IF v_other IS NOT NULL THEN
        RAISE EXCEPTION 'Student % is already in team % for project %', NEW.usn, v_other, v_project
            USING ERRCODE = 'unique_violation', CONSTRAINT = 'one_team_per_project',
                  DETAIL = 'one_team_per_project';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_team_one_per_project
BEFORE INSERT OR UPDATE OF team_id, usn ON team_member
FOR EACH ROW EXECUTE FUNCTION private.enforce_one_team_per_project();

-- The same rule from the team side: moving a team that has members to another project
-- could put a student in two teams of one project, so a staffed team's project is fixed.
