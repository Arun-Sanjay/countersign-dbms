-- pgvector, and the integrity triggers that a CHECK constraint cannot express.
--
-- Append-only on top of 0001 (= the graded fixture schema): only ADD tables, columns,
-- constraints, defaults and indexes. Fixture columns are never dropped or renamed,
-- so Q1–Q37 still run unchanged against the fixture data.
-- RLS is enabled on every new table (default-deny); policies arrive in 0003.

CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA extensions;

-- Internal schema: NOT exposed through the Data API (config.toml [api].schemas).
-- Holds private notes and the integrity trigger functions. Trigger functions fire
-- without EXECUTE/USAGE grants, so callers never need access to this schema.
CREATE SCHEMA IF NOT EXISTS private;
REVOKE ALL ON SCHEMA private FROM PUBLIC, anon, authenticated;


-- =====================================================================
-- 1. Identity: auth.users -> role -> (student | faculty)
-- =====================================================================
CREATE TABLE app_user (
    user_id    UUID         PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    role       VARCHAR(10)  NOT NULL CHECK (role IN ('student', 'faculty', 'admin')),
    usn        VARCHAR(10)  UNIQUE REFERENCES student(usn)        ON DELETE RESTRICT,
    faculty_id VARCHAR(6)   UNIQUE REFERENCES faculty(faculty_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- exactly the identifier that matches the role (a student has a USN, faculty an id)
    CONSTRAINT app_user_role_consistency CHECK (
           (role = 'student' AND usn IS NOT NULL AND faculty_id IS NULL)
        OR (role = 'faculty' AND faculty_id IS NOT NULL AND usn IS NULL)
        OR (role = 'admin'   AND usn IS NULL AND faculty_id IS NULL))
);


-- =====================================================================
-- 2. Term, offering, enrollment (course.faculty_id alone means "one teacher forever")
-- =====================================================================
CREATE TABLE academic_term (
    term_id    VARCHAR(10) PRIMARY KEY,                  -- e.g. '2026-ODD'
    name       VARCHAR(40) NOT NULL,
    start_date DATE        NOT NULL,
    end_date   DATE        NOT NULL,
    CHECK (end_date > start_date),
    -- exclusion constraint: no two terms may overlap in time
    CONSTRAINT academic_term_no_overlap
        EXCLUDE USING gist (daterange(start_date, end_date, '[]') WITH &&)
);

CREATE TABLE course_offering (
    offering_id INT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(10) NOT NULL REFERENCES course(course_code)    ON DELETE RESTRICT,
    term_id     VARCHAR(10) NOT NULL REFERENCES academic_term(term_id) ON DELETE RESTRICT,
    section     CHAR(1)     NOT NULL,
    faculty_id  VARCHAR(6)  NOT NULL REFERENCES faculty(faculty_id)    ON DELETE RESTRICT,
    CONSTRAINT course_offering_natural_key UNIQUE (course_code, term_id, section),
    -- superkey that lets project reference (offering_id, course_code) together
    CONSTRAINT course_offering_id_course_key UNIQUE (offering_id, course_code)
);

CREATE TABLE enrollment (                         -- STUDENT <-> COURSE_OFFERING (M:N)
    usn         VARCHAR(10) REFERENCES student(usn)                 ON DELETE RESTRICT,
    offering_id INT         REFERENCES course_offering(offering_id) ON DELETE RESTRICT,
    enrolled_on DATE        NOT NULL DEFAULT CURRENT_DATE,
    PRIMARY KEY (usn, offering_id)
);

-- A project may belong to an offering. The composite FK also forces the offering to be
-- of the project's own course (MATCH SIMPLE: not checked while offering_id IS NULL).
ALTER TABLE project
    ADD COLUMN offering_id INT,
    ADD CONSTRAINT project_offering_fkey FOREIGN KEY (offering_id, course_code)
        REFERENCES course_offering(offering_id, course_code) ON DELETE RESTRICT;


-- =====================================================================
-- 3. Team and artifact
-- =====================================================================
-- UNIQUE(team_id, project_id) is a superkey (team_id alone is the PK). It exists only so
-- children can carry (team_id, project_id) and be checked by a composite FK: a deliberate,
-- documented denormalization that stops "T03 artifact filed under a P01 milestone".
ALTER TABLE team
    ADD CONSTRAINT team_id_project_key UNIQUE (team_id, project_id),
    ADD COLUMN topic_title VARCHAR(120),
    ADD COLUMN abstract    TEXT,
    ALTER COLUMN created_at SET DEFAULT CURRENT_DATE,
    -- history: deleting a project must not silently wipe its teams' work (was CASCADE)
    DROP CONSTRAINT team_project_id_fkey,
    ADD CONSTRAINT team_project_id_fkey FOREIGN KEY (project_id)
        REFERENCES project(project_id) ON DELETE RESTRICT;

-- role is a two-value domain, and a team has at most one lead (partial UNIQUE index).
-- The fixture data uses exactly 'lead' / 'member' with one lead per team.
ALTER TABLE team_member
    ALTER COLUMN joined_at SET DEFAULT CURRENT_DATE,
    ADD CONSTRAINT team_member_role_check CHECK (role IN ('lead', 'member'));
CREATE UNIQUE INDEX team_member_one_lead ON team_member (team_id) WHERE role = 'lead';

ALTER TABLE artifact
    ADD COLUMN visibility   VARCHAR(10) NOT NULL DEFAULT 'team'
        CHECK (visibility IN ('private', 'team', 'submitted')),
    ADD COLUMN owner_usn    VARCHAR(10) REFERENCES student(usn) ON DELETE RESTRICT,
    ADD COLUMN external_ref TEXT,                                 -- Docs/draw.io/GitHub URL
    ADD CONSTRAINT artifact_private_needs_owner CHECK (visibility <> 'private' OR owner_usn IS NOT NULL),
    -- history: an artifact outlives nothing silently; deleting its team is refused (was CASCADE)
    DROP CONSTRAINT artifact_team_id_fkey,
    ADD CONSTRAINT artifact_team_id_fkey FOREIGN KEY (team_id) REFERENCES team(team_id) ON DELETE RESTRICT,
    ADD CONSTRAINT artifact_team_project_fkey FOREIGN KEY (team_id, project_id)
        REFERENCES team(team_id, project_id) ON DELETE RESTRICT,
    ALTER COLUMN created_at SET DEFAULT CURRENT_DATE;

-- Weak entity ARTIFACT_VERSION: identified by (owner artifact, version_no).
CREATE TABLE artifact_version (
    artifact_id   VARCHAR(5)  NOT NULL REFERENCES artifact(artifact_id) ON DELETE CASCADE,
    version_no    INT         NOT NULL CHECK (version_no > 0),
    created_by    VARCHAR(10) NOT NULL REFERENCES student(usn) ON DELETE RESTRICT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    content_hash  CHAR(64)    CHECK (content_hash ~ '^[0-9a-f]{64}$'),  -- sha256 hex
    mongo_ref     TEXT,                                   -- note_versions/_id in MongoDB
    ai_assistance VARCHAR(10) NOT NULL DEFAULT 'none'
        CHECK (ai_assistance IN ('none', 'assisted', 'generated')),
    PRIMARY KEY (artifact_id, version_no)
);


-- =====================================================================
-- 4. Contribution: ingest-grade (identity id, source, idempotency key)
-- =====================================================================
ALTER TABLE contribution ALTER COLUMN contribution_id ADD GENERATED BY DEFAULT AS IDENTITY;
-- Rows inserted with explicit ids (fixture seed) do not advance the sequence: move it past max.
SELECT setval(pg_get_serial_sequence('public.contribution', 'contribution_id'),
              COALESCE(max(contribution_id), 0) + 1, false)
FROM contribution;

ALTER TABLE contribution
    ADD COLUMN source      VARCHAR(10) NOT NULL DEFAULT 'manual'
        CHECK (source IN ('manual', 'github', 'obsidian', 'editor')),
    ADD COLUMN source_ref  TEXT,                     -- commit SHA / note version id
    ADD COLUMN occurred_at TIMESTAMPTZ,              -- precise event time (fixture rows: date only)
    ADD COLUMN ai_assisted BOOLEAN     NOT NULL DEFAULT false,
    ALTER COLUMN created_at SET DEFAULT CURRENT_DATE,
    -- history: a student with recorded work cannot be deleted (was CASCADE)
    DROP CONSTRAINT contribution_usn_fkey,
    ADD CONSTRAINT contribution_usn_fkey FOREIGN KEY (usn) REFERENCES student(usn) ON DELETE RESTRICT,
    -- ... and neither can the artifact the work was done on (was CASCADE)
    DROP CONSTRAINT contribution_artifact_id_fkey,
    ADD CONSTRAINT contribution_artifact_id_fkey FOREIGN KEY (artifact_id)
        REFERENCES artifact(artifact_id) ON DELETE RESTRICT,
    -- superkey (contribution_id is the PK) so skill_evidence can reference (contribution_id, usn)
    ADD CONSTRAINT contribution_id_usn_key UNIQUE (contribution_id, usn);

-- Idempotency key: a redelivered webhook hits ON CONFLICT DO NOTHING instead of duplicating.
CREATE UNIQUE INDEX contribution_idempotency_key
    ON contribution (source, source_ref, usn, artifact_id) WHERE source_ref IS NOT NULL;


-- =====================================================================
-- 5. Assessment at component grain (the paper marks sheet)
-- =====================================================================
-- cie_part says which part of the lab CIE a component feeds:
--   reduced    -> C1..C9, summed and scaled 120 raw -> 30
--   innovative -> C10 (out of 10)        final -> C11 (out of 10)
-- counts_in_reduced is a GENERATED (derived) column, so the two can never disagree.
ALTER TABLE milestone
    ADD COLUMN cie_part VARCHAR(10) NOT NULL DEFAULT 'reduced'
        CHECK (cie_part IN ('reduced', 'innovative', 'final')),
    ADD COLUMN counts_in_reduced BOOLEAN GENERATED ALWAYS AS (cie_part = 'reduced') STORED,
    ADD COLUMN locked_at         TIMESTAMPTZ,                    -- set => marks are final
    -- the two non-reduced parts are added as-is to the /50 total, so they must be out of 10
    ADD CONSTRAINT milestone_cie_part_out_of_10 CHECK (cie_part = 'reduced' OR max_marks = 10);
-- at most one 'innovative' and one 'final' component per project
CREATE UNIQUE INDEX milestone_one_cie_part ON milestone (project_id, cie_part) WHERE cie_part <> 'reduced';

CREATE TABLE submission (
    submission_id INT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id       VARCHAR(5)  NOT NULL,
    project_id    VARCHAR(5)  NOT NULL,
    milestone_no  INT         NOT NULL,
    submitted_by  VARCHAR(10) NOT NULL REFERENCES student(usn) ON DELETE RESTRICT,
    submitted_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Resubmission: a team may submit a component again until it is locked. Each attempt
    -- is a new row; the old frozen versions stay as history.
    attempt_no    INT         NOT NULL DEFAULT 1 CHECK (attempt_no > 0),
    -- one row per (team, component, attempt). team_id -> project_id, so the key is a
    -- superkey of (team_id, milestone_no, attempt_no); the column order also indexes the
    -- composite FK below.
    CONSTRAINT submission_attempt_key UNIQUE (team_id, project_id, milestone_no, attempt_no),
    FOREIGN KEY (team_id, project_id)      REFERENCES team(team_id, project_id)            ON DELETE RESTRICT,
    FOREIGN KEY (project_id, milestone_no) REFERENCES milestone(project_id, milestone_no) ON DELETE RESTRICT
);

-- Which frozen artifact version was submitted (M:N SUBMISSION <-> ARTIFACT_VERSION).
CREATE TABLE submission_artifact (
    submission_id INT        NOT NULL REFERENCES submission(submission_id) ON DELETE CASCADE,
    artifact_id   VARCHAR(5) NOT NULL,
    version_no    INT        NOT NULL,
    PRIMARY KEY (submission_id, artifact_id),
    FOREIGN KEY (artifact_id, version_no)
        REFERENCES artifact_version(artifact_id, version_no) ON DELETE RESTRICT
);

CREATE TABLE assessment (
    usn          VARCHAR(10)  NOT NULL REFERENCES student(usn) ON DELETE RESTRICT,
    project_id   VARCHAR(5)   NOT NULL,
    milestone_no INT          NOT NULL,
    marks        NUMERIC(4,1) NOT NULL CHECK (marks >= 0),     -- upper bound: trigger below
    assessed_by  VARCHAR(6)   NOT NULL REFERENCES faculty(faculty_id) ON DELETE RESTRICT,
    assessed_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    remarks      VARCHAR(200),
    PRIMARY KEY (usn, project_id, milestone_no),
    FOREIGN KEY (project_id, milestone_no) REFERENCES milestone(project_id, milestone_no) ON DELETE RESTRICT
);


-- =====================================================================
-- 6. Claims, evidence, countersign ("every mark has a receipt")
-- =====================================================================
CREATE TABLE claim (
    claim_id      INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usn           VARCHAR(10)  NOT NULL REFERENCES student(usn) ON DELETE RESTRICT,
    team_id       VARCHAR(5)   NOT NULL,
    project_id    VARCHAR(5)   NOT NULL,
    milestone_no  INT          NOT NULL,
    statement     VARCHAR(500) NOT NULL CHECK (length(btrim(statement)) >= 10),
    -- the kind of work claimed (same domain as the fixture's contribution.contribution_type)
    contribution_type VARCHAR(15)
        CHECK (contribution_type IN ('research', 'design', 'code', 'documentation', 'review')),
    ai_assistance VARCHAR(10)  NOT NULL DEFAULT 'none'
        CHECK (ai_assistance IN ('none', 'assisted', 'generated')),
    -- derived attribute, stored for fast queues; maintained only by triggers
    status        VARCHAR(10)  NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'confirmed', 'contested')),
    -- bumped by trigger whenever the text or the evidence list changes; a countersign
    -- records the revision it endorses (optimistic concurrency, see check_countersign)
    revision      INT          NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- superkey (claim_id is the PK) so skill_evidence can reference (claim_id, usn)
    CONSTRAINT claim_id_usn_key UNIQUE (claim_id, usn),
    FOREIGN KEY (team_id, project_id)      REFERENCES team(team_id, project_id)            ON DELETE RESTRICT,
    FOREIGN KEY (project_id, milestone_no) REFERENCES milestone(project_id, milestone_no) ON DELETE RESTRICT
);

-- Weak entity CLAIM_EVIDENCE: identified by (owner claim, evidence_no).
CREATE TABLE claim_evidence (
    claim_id        INT          NOT NULL REFERENCES claim(claim_id) ON DELETE CASCADE,
    evidence_no     INT          NOT NULL CHECK (evidence_no > 0),
    kind            VARCHAR(16)  NOT NULL
        CHECK (kind IN ('contribution', 'artifact_version', 'commit', 'url', 'file')),
    contribution_id INT          REFERENCES contribution(contribution_id) ON DELETE RESTRICT,
    artifact_id     VARCHAR(5),
    version_no      INT,
    ref             TEXT,                                  -- commit SHA, URL or file path
    note            VARCHAR(200),
    added_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (claim_id, evidence_no),
    FOREIGN KEY (artifact_id, version_no)
        REFERENCES artifact_version(artifact_id, version_no) ON DELETE RESTRICT,
    -- exactly the pointer that matches the kind is filled in
    CONSTRAINT claim_evidence_kind_matches CHECK (CASE kind
        WHEN 'contribution'     THEN contribution_id IS NOT NULL AND num_nulls(artifact_id, version_no, ref) = 3
        WHEN 'artifact_version' THEN num_nonnulls(artifact_id, version_no) = 2 AND num_nulls(contribution_id, ref) = 2
        ELSE ref IS NOT NULL AND num_nulls(contribution_id, artifact_id, version_no) = 3 END),
    -- free-text refs are still typed: a commit is a hex SHA, a URL is http(s) only
    -- (so no javascript: links can be stored and later rendered)
    CONSTRAINT claim_evidence_ref_format CHECK (CASE kind
        WHEN 'commit' THEN ref ~ '^[0-9a-f]{7,40}$'
        WHEN 'url'    THEN ref ~* '^https?://\S+$'
        ELSE true END)
);
-- the same pointer cannot be cited twice by one claim
CREATE UNIQUE INDEX claim_evidence_once_contribution ON claim_evidence (claim_id, contribution_id)
    WHERE contribution_id IS NOT NULL;
CREATE UNIQUE INDEX claim_evidence_once_version ON claim_evidence (claim_id, artifact_id, version_no)
    WHERE artifact_id IS NOT NULL;

CREATE TABLE countersign (
    claim_id     INT          NOT NULL REFERENCES claim(claim_id) ON DELETE CASCADE,
    endorser_usn VARCHAR(10)  NOT NULL REFERENCES student(usn) ON DELETE RESTRICT,
    verdict      VARCHAR(8)   NOT NULL CHECK (verdict IN ('confirm', 'dispute')),
    comment      VARCHAR(300),
    claim_revision INT        NOT NULL,                      -- claim.revision that was endorsed
    signed_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (claim_id, endorser_usn),
    CONSTRAINT countersign_dispute_needs_comment CHECK (verdict = 'confirm' OR comment IS NOT NULL)
);


