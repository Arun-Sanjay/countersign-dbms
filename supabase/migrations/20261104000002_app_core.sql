    UPDATE public.claim SET revision = revision + 1
    WHERE claim_id = CASE WHEN TG_OP = 'DELETE' THEN OLD.claim_id ELSE NEW.claim_id END;
    RETURN NULL;
END $$;

CREATE TRIGGER trg_claim_evidence_revision
