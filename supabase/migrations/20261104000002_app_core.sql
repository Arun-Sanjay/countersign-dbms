            USING ERRCODE = 'check_violation', CONSTRAINT = 'team_project_immutable',
                  DETAIL = 'team_project_immutable';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_team_project_guard
BEFORE UPDATE OF project_id ON team
FOR EACH ROW EXECUTE FUNCTION private.guard_team_project();

-- ---- (c2) History pins membership ----
-- A student who has recorded anything in a team (claims, countersigns, contributions,
-- versions, chunks, owned artifacts, submissions, or marks in the project) cannot leave
-- it, by ANY path: the leave_team RPC, a direct DELETE through the API, or an UPDATE that
-- moves the row. Otherwise "the claimant / endorser / assessed student is a member" would
-- silently stop holding (and a leaver's countersign would still count).
-- The DELETE takes the row lock before this trigger runs, so it waits for any transaction
-- that wrote the row in assert_team_member, then (RC) sees that one's work or (RR) gets 40001.
-- A cascade from deleting the STUDENT is let through: every history table references
-- student ON DELETE RESTRICT, so that delete fails anyway with the proper FK error.
CREATE FUNCTION private.guard_member_history()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE v_project VARCHAR(5);
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.team_id = OLD.team_id AND NEW.usn = OLD.usn THEN
        RETURN NEW;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.student WHERE usn = OLD.usn) THEN
        RETURN OLD;                                  -- cascade from deleting the student
    END IF;
    SELECT project_id INTO v_project FROM public.team WHERE team_id = OLD.team_id;

    IF EXISTS (SELECT 1 FROM public.claim WHERE team_id = OLD.team_id AND usn = OLD.usn)
       OR EXISTS (SELECT 1 FROM public.countersign cs JOIN public.claim c ON c.claim_id = cs.claim_id
                  WHERE c.team_id = OLD.team_id AND cs.endorser_usn = OLD.usn)
       OR EXISTS (SELECT 1 FROM public.artifact a
                  WHERE a.team_id = OLD.team_id
                    AND (a.owner_usn = OLD.usn
                         OR EXISTS (SELECT 1 FROM public.contribution k
                                    WHERE k.artifact_id = a.artifact_id AND k.usn = OLD.usn)
                         OR EXISTS (SELECT 1 FROM public.artifact_version v
                                    WHERE v.artifact_id = a.artifact_id AND v.created_by = OLD.usn)
                         OR EXISTS (SELECT 1 FROM public.artifact_chunk ch
                                    WHERE ch.artifact_id = a.artifact_id AND ch.author_usn = OLD.usn)))
       OR EXISTS (SELECT 1 FROM public.submission WHERE team_id = OLD.team_id AND submitted_by = OLD.usn)
       OR EXISTS (SELECT 1 FROM public.assessment WHERE project_id = v_project AND usn = OLD.usn) THEN
        RAISE EXCEPTION 'Student % has recorded work in team %, so the membership cannot be removed',
            OLD.usn, OLD.team_id
            USING ERRCODE = 'object_not_in_prerequisite_state', CONSTRAINT = 'leave_team_has_history',
                  DETAIL = 'leave_team_has_history',
                  HINT = 'Claims, countersigns, contributions and marks stay with the team they were made in.';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;

CREATE TRIGGER trg_team_member_history_guard
BEFORE DELETE OR UPDATE OF team_id, usn ON team_member
FOR EACH ROW EXECUTE FUNCTION private.guard_member_history();

