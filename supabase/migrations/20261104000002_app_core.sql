-- ---- (f) What a submission may freeze ----
-- The artifact must be the submitting team's, filed under the same component, not private,
-- and the component must still be open (a locked component's submission is frozen).
CREATE FUNCTION private.check_submission_artifact()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE s RECORD; a RECORD;
BEGIN
    SELECT team_id, project_id, milestone_no INTO s
    FROM public.submission WHERE submission_id = NEW.submission_id;
    SELECT team_id, milestone_no, visibility INTO a
    FROM public.artifact WHERE artifact_id = NEW.artifact_id;
    IF s.team_id IS NULL OR a.team_id IS NULL THEN
        RETURN NEW;                                  -- the FK reports a missing parent
    END IF;
    IF s.team_id <> a.team_id THEN
        RAISE EXCEPTION 'Artifact % belongs to team %, not the submitting team %',
            NEW.artifact_id, a.team_id, s.team_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'submission_artifact_same_team',
                  DETAIL = 'submission_artifact_same_team';
    END IF;
    IF a.milestone_no <> s.milestone_no THEN
        RAISE EXCEPTION 'Artifact % is filed under component %, not the submitted component %',
            NEW.artifact_id, a.milestone_no, s.milestone_no
            USING ERRCODE = 'check_violation', CONSTRAINT = 'submission_artifact_same_component',
                  DETAIL = 'submission_artifact_same_component';
    END IF;
    IF a.visibility = 'private' THEN
        RAISE EXCEPTION 'Artifact % is private; share it with the team before submitting', NEW.artifact_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'submission_artifact_not_private',
                  DETAIL = 'artifact_private';
    END IF;
    PERFORM private.assert_milestone_open(s.project_id, s.milestone_no, 'its submissions');
    RETURN NEW;
END $$;

CREATE TRIGGER trg_submission_artifact_check
BEFORE INSERT OR UPDATE ON submission_artifact
FOR EACH ROW EXECUTE FUNCTION private.check_submission_artifact();

