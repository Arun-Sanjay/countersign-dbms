-- ---- (e) Assessment: marks <= milestone.max_marks, nothing changes once locked ----
-- FOR SHARE on the milestone row: a concurrent "lock milestone" UPDATE must wait for this
-- transaction (or we wait for it and then see locked_at), so no mark slips in at lock time.
CREATE FUNCTION private.check_assessment()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE m RECORD;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        SELECT locked_at INTO m FROM public.milestone
        WHERE project_id = OLD.project_id AND milestone_no = OLD.milestone_no FOR SHARE;
        IF m.locked_at IS NOT NULL THEN
            RAISE EXCEPTION 'Milestone %/% is locked (since %); marks can no longer change',
                OLD.project_id, OLD.milestone_no, m.locked_at
                USING ERRCODE = 'object_not_in_prerequisite_state', CONSTRAINT = 'milestone_locked', DETAIL = 'milestone_locked';
        END IF;
        IF TG_OP = 'DELETE' THEN
            RETURN OLD;
        END IF;
    END IF;

    SELECT max_marks, locked_at INTO m FROM public.milestone
    WHERE project_id = NEW.project_id AND milestone_no = NEW.milestone_no FOR SHARE;
    IF NOT FOUND THEN
        RETURN NEW;                                  -- the FK reports a missing milestone
    END IF;
    IF m.locked_at IS NOT NULL THEN
        RAISE EXCEPTION 'Milestone %/% is locked (since %); marks can no longer change',
            NEW.project_id, NEW.milestone_no, m.locked_at
            USING ERRCODE = 'object_not_in_prerequisite_state', CONSTRAINT = 'milestone_locked', DETAIL = 'milestone_locked';
    END IF;
    IF NEW.marks > m.max_marks THEN
        RAISE EXCEPTION 'Marks % exceed the maximum % for milestone %/%',
            NEW.marks, m.max_marks, NEW.project_id, NEW.milestone_no
            USING ERRCODE = 'check_violation', CONSTRAINT = 'assessment_marks_le_max', DETAIL = 'assessment_marks_le_max';
    END IF;
    -- the assessed student must be in some team of this project; the no-op UPDATE writes
    -- that membership row (same write-skew reasoning as assert_team_member)
    UPDATE public.team_member tm SET role = tm.role
    FROM public.team t
    WHERE t.team_id = tm.team_id AND tm.usn = NEW.usn AND t.project_id = NEW.project_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Student % is not in any team of project %', NEW.usn, NEW.project_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'assessment_member_required',
                  DETAIL = 'assessment_member_required';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_assessment_check
BEFORE INSERT OR UPDATE OR DELETE ON assessment
FOR EACH ROW EXECUTE FUNCTION private.check_assessment();

-- The same invariant from the other side: lowering max_marks must not strand a mark above it.
