-- ---- (g) Claims: lock, finality and revision ----
-- A claim on a locked component cannot be filed, edited, moved or withdrawn (any path).
-- Once a teammate has countersigned it (status <> pending) its content is final.
-- Every content change bumps claim.revision, which countersigns are bound to.
CREATE FUNCTION private.guard_claim()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        PERFORM private.assert_milestone_open(NEW.project_id, NEW.milestone_no, 'its claims');
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        PERFORM private.assert_milestone_open(OLD.project_id, OLD.milestone_no, 'its claims');
        RETURN OLD;
    END IF;
    -- UPDATE: status (derived) and revision (bookkeeping) are not content
    IF (to_jsonb(NEW) - 'status' - 'revision') = (to_jsonb(OLD) - 'status' - 'revision') THEN
        RETURN NEW;
    END IF;
    IF OLD.status <> 'pending' THEN
        RAISE EXCEPTION 'Claim % is already %; a countersigned claim cannot change', OLD.claim_id, OLD.status
            USING ERRCODE = 'object_not_in_prerequisite_state', CONSTRAINT = 'claim_not_pending',
                  DETAIL = 'claim_not_pending';
    END IF;
    PERFORM private.assert_milestone_open(OLD.project_id, OLD.milestone_no, 'its claims');
    IF (NEW.project_id, NEW.milestone_no) IS DISTINCT FROM (OLD.project_id, OLD.milestone_no) THEN
        PERFORM private.assert_milestone_open(NEW.project_id, NEW.milestone_no, 'its claims');
    END IF;
    NEW.revision := OLD.revision + 1;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_claim_guard
BEFORE INSERT OR UPDATE OR DELETE ON claim
FOR EACH ROW EXECUTE FUNCTION private.guard_claim();

-- ---- (h) Evidence: frozen with its claim, from the claimant's team, own contributions ----
-- The claim row is locked (FOR NO KEY UPDATE), so evidence changes, edits and countersigns
-- of one claim happen one after another, never interleaved.
-- artifact_version evidence may be ANY version of the team's artifact (the statement says
-- which part was yours; the countersign judges it). A contribution, however, is a personal
-- record: a claim may cite only the claimant's own contributions.
CREATE FUNCTION private.check_claim_evidence()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
    c        RECORD;
    v_team   VARCHAR(5);
    v_author VARCHAR(10);
BEGIN
    SELECT usn, team_id, project_id, milestone_no, status INTO c
    FROM public.claim
    WHERE claim_id = CASE WHEN TG_OP = 'DELETE' THEN OLD.claim_id ELSE NEW.claim_id END
    FOR NO KEY UPDATE;
    IF NOT FOUND THEN                                -- cascade from deleting the claim,
        RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;   -- or the FK reports it
    END IF;
    IF c.status <> 'pending' THEN
        RAISE EXCEPTION 'Claim % is already %; its evidence is frozen',
            CASE WHEN TG_OP = 'DELETE' THEN OLD.claim_id ELSE NEW.claim_id END, c.status
            USING ERRCODE = 'object_not_in_prerequisite_state', CONSTRAINT = 'claim_not_pending',
                  DETAIL = 'claim_not_pending';
    END IF;
    PERFORM private.assert_milestone_open(c.project_id, c.milestone_no, 'its claims');
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    IF NEW.contribution_id IS NOT NULL THEN
        SELECT a.team_id, k.usn INTO v_team, v_author
        FROM public.contribution k JOIN public.artifact a ON a.artifact_id = k.artifact_id
        WHERE k.contribution_id = NEW.contribution_id;
    ELSIF NEW.artifact_id IS NOT NULL THEN
        SELECT team_id INTO v_team FROM public.artifact WHERE artifact_id = NEW.artifact_id;
    END IF;
    IF v_team <> c.team_id THEN
        RAISE EXCEPTION 'Evidence belongs to team %, but claim % is for team %', v_team, NEW.claim_id, c.team_id
            USING ERRCODE = 'check_violation', CONSTRAINT = 'claim_evidence_same_team',
                  DETAIL = 'claim_evidence_same_team';
    END IF;
    IF v_author <> c.usn THEN
        RAISE EXCEPTION 'Contribution % was made by %, not by the claimant %', NEW.contribution_id, v_author, c.usn
            USING ERRCODE = 'check_violation', CONSTRAINT = 'claim_evidence_own_contribution',
                  DETAIL = 'claim_evidence_own_contribution';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_claim_evidence_check
BEFORE INSERT OR UPDATE OR DELETE ON claim_evidence
FOR EACH ROW EXECUTE FUNCTION private.check_claim_evidence();

