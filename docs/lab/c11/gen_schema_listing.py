"""Generate docs/lab/c11/schema_listing.md (Appendix A of C11_Final_Report.md) from the
catalog of the LOCAL Supabase database (container supabase_db_countersign-dbms), which has
the same migrations 0001-0007 as the cloud project. Read only: the session runs with
default_transaction_read_only = on. Run by build_c9_c11.sh, or by hand:
    python3 docs/lab/c11/gen_schema_listing.py [container]
"""
import json
import subprocess
import sys
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONTAINER = sys.argv[1] if len(sys.argv) > 1 else "supabase_db_countersign-dbms"
WRAP = 84                      # characters per code line (fits A4 at the 0.85 mono scale)
KIND = {"p": "PRIMARY KEY", "u": "UNIQUE", "f": "FOREIGN KEY", "c": "CHECK", "x": "EXCLUDE", "t": "TRIGGER"}
VOL = {"i": "immutable", "s": "stable", "v": "volatile"}


def catalog():
    sql = (HERE / "catalog.sql").read_text()
    out = subprocess.run(
        ["docker", "exec", "-i", "-e", "PGOPTIONS=-c default_transaction_read_only=on", CONTAINER,
         "psql", "-U", "postgres", "-d", "postgres", "-X", "-q", "-At", "-v", "ON_ERROR_STOP=1", "-f", "-"],
        input=sql, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def esc(s):
    """Escape text for a pandoc pipe-table cell (plain text, may wrap)."""
    s = s or ""
    for ch in "\\`*_[]<>|#$~^":
        s = s.replace(ch, "\\" + ch)
    return s


def wrap(line):
    return textwrap.wrap(line, WRAP, subsequent_indent="      ", break_long_words=True,
                         break_on_hyphens=False) or [""]


def column_default(c):
    if c["identity"]:
        return "identity (" + ("always" if c["identity"] == "a" else "by default") + ")"
    if c["generated"]:
        return "generated (see below)"
    d = c["default"] or ""
    return d if len(d) <= 40 else d[:37] + "..."


def table_md(i, t):
    out = [f"### A.{i} `{t['schema']}.{t['name']}`", ""]
    pol = t["policies"] or []
    rls = "on" + (", forced" if t["force_rls"] else "") if t["rls"] else "off"
    def n(k, word):
        return f"{k} {word}" + ("" if k == 1 else "s")
    out.append(f"Row-level security {rls}; {n(len(t['columns']), 'column')}; "
               f"{n(len(t['constraints'] or []), 'constraint')}; {n(len(pol), 'policy').replace('policys', 'policies')}; "
               f"{n(len(t['triggers'] or []), 'trigger')}.")
    out += ["", "| Column | Type | Nullable | Default |", "|:--|:--|:-:|:--|"]
    for c in t["columns"]:
        out.append(f"| {esc(c['name'])} | {esc(c['type'])} | {'no' if c['notnull'] else 'yes'} | "
                   f"{esc(column_default(c))} |")
    lines = []
    for c in t["columns"]:
        if c["generated"]:
            lines += wrap(f"GENERATED {c['name']} = {c['default']} STORED")
    for k in t["constraints"] or []:
        lines += wrap(f"{KIND.get(k['type'], k['type'])} {k['name']}: {k['def']}")
    for ix in t["indexes"] or []:
        lines += wrap("INDEX " + ix.split(" ON ", 1)[0].split()[-1] + ": USING" + ix.split(" USING", 1)[1])
    for tg in t["triggers"] or []:
        lines += wrap("TRIGGER " + tg)
    for p in pol:
        roles = p["roles"].strip("{}")
        lines += wrap(f"POLICY {p['name']}: FOR {p['cmd']} TO {roles}"
                      + ("" if p["permissive"] == "PERMISSIVE" else " (restrictive)"))
    out += ["", "```text", *lines, "```", ""]
    return out


def main():
    d = catalog()
    t_all = d["tables"]
    md = [
        "<!-- generated by docs/lab/c11/gen_schema_listing.py from the local database catalog; do not edit -->",
        "",
        f"Generated from the catalog of the local Supabase database (PostgreSQL {d['server']}), "
        f"migrations {', '.join(d['migrations'])}, the same set that is applied to the cloud "
        f"project. {len(t_all)} base tables, {len(d['views'])} views and {len(d['functions'])} "
        "functions in the schemas `public`, `private` and `app`. Per table: the columns, then "
        "every constraint, extra index, trigger and RLS policy, as PostgreSQL prints them "
        "(`pg_get_constraintdef`, `pg_get_indexdef`, `pg_get_triggerdef`, `pg_policies`). "
        "Long column defaults are shortened with an ellipsis in the column table.",
        "",
    ]
    for i, t in enumerate(t_all, 1):
        md += table_md(i, t)
    md += [f"### A.{len(t_all) + 1} Views", "", "| View | Columns | Options |", "|:--|--:|:--|"]
    for v in d["views"]:
        md.append(f"| `{v['schema']}.{v['name']}` | {v['columns']} | {esc((v['options'] or '').strip('{}'))} |")
    md += ["", f"### A.{len(t_all) + 2} Functions", "",
           "Security: *definer* functions run with the owner's rights and set `search_path = ''`; "
           "*invoker* functions run as the caller, so RLS applies inside them.", "",
           "```text"]
    for f in d["functions"]:
        sec = "DEFINER" if f["definer"] else "invoker"
        md += wrap(f"{f['schema']}.{f['name']}({f['args']}) -> {f['returns']}  "
                   f"[{f['lang']}, {VOL[f['volatility']]}, {sec}]")
    md += ["```", ""]
    (HERE / "schema_listing.md").write_text("\n".join(md))
    print(f"schema_listing.md: {len(t_all)} tables, {len(d['views'])} views, {len(d['functions'])} functions")


if __name__ == "__main__":
    main()
